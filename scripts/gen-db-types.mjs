// Generates packages/db-types/src/database.ts by introspecting a Postgres database.
// Output follows the structure of `supabase gen types typescript`, which remains the
// official command (`pnpm db:types`). Use this one where the Supabase CLI/Docker is unavailable:
//   DATABASE_URL=postgres://... node scripts/gen-db-types.mjs
import pg from "pg";
import { writeFileSync } from "node:fs";

const client = new pg.Client({ connectionString: process.env.DATABASE_URL });
await client.connect();
const q = async (sql) => (await client.query(sql)).rows;

const enums = await q(`
  select t.typname as name, array_agg(e.enumlabel::text order by e.enumsortorder) as labels
    from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
   where n.nspname = 'public' group by t.typname order by t.typname`);
const enumNames = new Set(enums.map((e) => e.name));

const typeInfo = await q(`
  select t.oid, t.typname, t.typtype, t.typcategory, e.typname as elem, c.relname as composite
    from pg_type t left join pg_type e on e.oid = t.typelem
    left join pg_class c on c.oid = t.typrelid and t.typtype = 'c'`);
const byOid = new Map(typeInfo.map((t) => [String(t.oid), t]));

const scalar = (name) => {
  if (enumNames.has(name)) return `Database["public"]["Enums"]["${name}"]`;
  if (["uuid", "text", "varchar", "bpchar", "date", "timestamptz", "timestamp", "time", "citext"].includes(name)) return "string";
  if (["int2", "int4", "int8", "float4", "float8", "numeric"].includes(name)) return "number";
  if (name === "bool") return "boolean";
  if (name === "json" || name === "jsonb") return "Json";
  if (name === "void") return "undefined";
  return "unknown";
};
const tsType = (oid, tables) => {
  const t = byOid.get(String(oid));
  if (!t) return "unknown";
  if (t.typcategory === "A") return `${scalar(t.elem)}[]`;
  if (t.typtype === "c" && tables.has(t.composite)) return `Database["public"]["Tables"]["${t.composite}"]["Row"]`;
  return scalar(t.typname);
};

const rels = await q(`
  select c.relname as name, c.relkind as kind,
         json_agg(json_build_object('col', a.attname, 'oid', a.atttypid, 'notnull', a.attnotnull,
                  'hasdef', a.atthasdef or a.attidentity <> '' or a.attgenerated <> '') order by a.attnum) as cols
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
   where n.nspname = 'public' and c.relkind in ('r', 'v')
     and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
   group by c.relname, c.relkind order by c.relname`);
const tables = new Set(rels.filter((r) => r.kind === "r").map((r) => r.name));

const fns = await q(`
  select p.proname as name, p.proretset as setof, p.prorettype as ret,
         coalesce(p.proargnames, '{}')::text[] as argnames, p.proargtypes::oid[]::int8[] as argtypes, p.pronargdefaults as ndef
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.prokind = 'f' and p.prorettype <> 'trigger'::regtype
     and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')  -- skip extension functions
   order by p.proname`);

const ind = (n) => "  ".repeat(n);
let out = `// GENERATED by scripts/gen-db-types.mjs from the migrated schema. Do not edit by hand.
// Official regeneration: \`pnpm db:types\` (supabase gen types). Both produce this structure.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;
for (const r of rels.filter((r) => r.kind === "r")) {
  const row = r.cols.map((c) => `${ind(5)}${c.col}: ${tsType(c.oid, tables)}${c.notnull ? "" : " | null"}`).join("\n");
  const ins = r.cols.map((c) => `${ind(5)}${c.col}${c.notnull && !c.hasdef ? "" : "?"}: ${tsType(c.oid, tables)}${c.notnull ? "" : " | null"}`).join("\n");
  const upd = r.cols.map((c) => `${ind(5)}${c.col}?: ${tsType(c.oid, tables)}${c.notnull ? "" : " | null"}`).join("\n");
  out += `${ind(3)}${r.name}: {\n${ind(4)}Row: {\n${row}\n${ind(4)}}\n${ind(4)}Insert: {\n${ins}\n${ind(4)}}\n${ind(4)}Update: {\n${upd}\n${ind(4)}}\n${ind(4)}Relationships: []\n${ind(3)}}\n`;
}
out += `${ind(2)}}\n${ind(2)}Views: {\n`;
for (const r of rels.filter((r) => r.kind === "v")) {
  const row = r.cols.map((c) => `${ind(5)}${c.col}: ${tsType(c.oid, tables)} | null`).join("\n");
  out += `${ind(3)}${r.name}: {\n${ind(4)}Row: {\n${row}\n${ind(4)}}\n${ind(4)}Relationships: []\n${ind(3)}}\n`;
}
out += `${ind(2)}}\n${ind(2)}Functions: {\n`;
for (const f of fns) {
  const n = f.argtypes.length;
  const args = f.argtypes.map((oid, i) => {
    const optional = i >= n - f.ndef;
    return `${ind(5)}${f.argnames[i]}${optional ? "?" : ""}: ${tsType(oid, tables)}`;
  }).join("\n");
  const ret = tsType(f.ret, tables) + (f.setof ? "[]" : "");
  out += `${ind(3)}${f.name}: {\n${ind(4)}Args: ${n ? `{\n${args}\n${ind(4)}}` : "Record<PropertyKey, never>"}\n${ind(4)}Returns: ${ret}\n${ind(3)}}\n`;
}
out += `${ind(2)}}\n${ind(2)}Enums: {\n`;
for (const e of enums) out += `${ind(3)}${e.name}: ${e.labels.map((l) => JSON.stringify(l)).join(" | ")}\n`;
out += `${ind(2)}}\n${ind(2)}CompositeTypes: { [_ in never]: never }\n  }\n}

type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];
export type Views<T extends keyof PublicSchema["Views"]> = PublicSchema["Views"][T]["Row"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];
`;
writeFileSync(new URL("../packages/db-types/src/database.ts", import.meta.url), out);
await client.end();
console.log(`db types: ${tables.size} tables, ${rels.length - tables.size} views, ${fns.length} functions, ${enums.length} enums`);
